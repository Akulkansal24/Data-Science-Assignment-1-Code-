import os, time
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

SEED = 0
OUT = "out_q2"
os.makedirs(OUT, exist_ok=True)
LOG = open(os.path.join(OUT, "results_q2.txt"), "w")


def say(*a):
    s = " ".join(str(x) for x in a)
    print(s, flush=True)
    LOG.write(s + "\n"); LOG.flush()


# --------------------------------------------------------------------------
# Data: build D (one-hot, drop constants, min-max) and y
# --------------------------------------------------------------------------
def build_data():
    if os.environ.get("SYNTH") == "1":
        rng = np.random.default_rng(123)
        n, d = 60000, 30
        D = rng.random((n, d))
        D[:, -3:] = D[:, :3] * 2.0 + D[:, 3:6]          # make D rank-deficient
        y = (D @ rng.normal(size=d) + 0.5 * rng.normal(size=n) > 1.0).astype(float)
        return D, y
    from sklearn.datasets import fetch_kddcup99
    kdd = fetch_kddcup99(subset=None, as_frame=True)
    X = kdd.data.copy()
    cat = ["protocol_type", "service", "flag"]
    for c in cat:
        X[c] = X[c].apply(lambda v: v.decode() if isinstance(v, bytes) else v)
    Xc = pd.get_dummies(X[cat], dtype=np.float64)                 # (i) one-hot
    Xn = X.drop(columns=cat).astype(np.float64)                   # (i) floats
    Dp = pd.concat([Xn, Xc], axis=1)
    Dp = Dp.loc[:, Dp.nunique() > 1]                              # (ii) drop constant cols
    Dp = (Dp - Dp.min()) / (Dp.max() - Dp.min())                  # (iii) min-max
    y = (kdd.target != b"normal.").to_numpy(dtype=float)
    return Dp.to_numpy(dtype=np.float64), y


D, y = build_data()
n, d = D.shape
say(f"D shape: n = {n}, d = {d}   (attack fraction in y = {y.mean():.4f})")

# Column-major copy of [D | y]: makes column-wise bincount sketching fast
Z = np.asfortranarray(np.column_stack([D, y]))


# --------------------------------------------------------------------------
# Helpers
# --------------------------------------------------------------------------
def loss(A, t, a):
    r = A @ a - t
    return float(r @ r)


def lstsq(A, t):
    return np.linalg.lstsq(A, t, rcond=None)[0]


def countsketch_matrix(Zmat, m, rng):
    """Return S@Zmat for a CountSketch S (m x N) WITHOUT forming S.
    Row i of Zmat is added with sign sigma(i) into row h(i) of the result.
    (np.bincount per column == np.add.at(out, h, sigma[:,None]*Zmat), just faster.)"""
    N = Zmat.shape[0]
    h = rng.integers(0, m, size=N)
    sg = rng.choice([-1.0, 1.0], size=N)
    out = np.empty((m, Zmat.shape[1]))
    for j in range(Zmat.shape[1]):
        out[:, j] = np.bincount(h, weights=sg * Zmat[:, j], minlength=m)
    return out


def countsketch_vector(v, m, rng):
    h = rng.integers(0, m, size=v.shape[0])
    sg = rng.choice([-1.0, 1.0], size=v.shape[0])
    return np.bincount(h, weights=sg * v, minlength=m)


# --------------------------------------------------------------------------
# (a) Full least squares
# --------------------------------------------------------------------------
say("\n=== (a) Full least squares ===")
t0 = time.perf_counter()
b = lstsq(D, y)
t_full = time.perf_counter() - t0
loss_full = loss(D, y, b)
rank_D = int(np.linalg.matrix_rank(D))
say(f"Loss(D,y,b) = {loss_full:.6f}")
say(f"Time to compute b = {t_full:.4f} s")
say(f"rank(D) = {rank_D}  (d = {d})")

# --------------------------------------------------------------------------
# (b) + (c) Sketch-and-solve over m, 5 repetitions
# --------------------------------------------------------------------------
say("\n=== (b),(c) CountSketch least squares ===")
M_LIST = [50, 100, 200, 500, 1000, 2000, 5000]
REPS = 5
rows = []
for m in M_LIST:
    for rep in range(REPS):
        rng = np.random.default_rng([SEED, 2, m, rep])
        t0 = time.perf_counter()
        SZ = countsketch_matrix(Z, m, rng)           # draws S and forms SD, Sy
        SD, Sy = SZ[:, :d], SZ[:, d]
        t_sketch = time.perf_counter() - t0
        t1 = time.perf_counter()
        a_t = lstsq(SD, Sy)
        t_solve = time.perf_counter() - t1
        t_total = t_sketch + t_solve
        L = loss(D, y, a_t)
        rows.append(dict(m=m, rep=rep, loss=L, ratio=L / loss_full,
                         sketched_loss=loss(SD, Sy, a_t),
                         t_sketch=t_sketch, t_solve=t_solve, t_total=t_total))
    say(f"m={m:5d} done")
R = pd.DataFrame(rows)
R.to_csv(os.path.join(OUT, "b_all_runs.csv"), index=False)

G = R.groupby("m")
summ = pd.DataFrame({
    "mean_loss": G["loss"].mean(),
    "mean_ratio": G["ratio"].mean(),
    "min_ratio": G["ratio"].min(),
    "max_ratio": G["ratio"].max(),
    "mean_sketched_loss": G["sketched_loss"].mean(),
    "mean_time_sketch": G["t_sketch"].mean(),
    "mean_time_solve": G["t_solve"].mean(),
    "mean_time_total": G["t_total"].mean(),
    "time_full_(a)": t_full,
    "speedup_vs_full": t_full / G["t_total"].mean(),
})
summ.to_csv(os.path.join(OUT, "b_c_summary.csv"))
pd.set_option("display.width", 220); pd.set_option("display.float_format", "{:.6g}".format)
say("\nPer-run table (b):\n" + R[["m", "rep", "loss", "ratio", "sketched_loss"]].to_string(index=False))
say("\nSummary (b) and timing (c):\n" + summ.to_string())

# Figure for (b): ratio vs m (log-log, min/max error bars) + sketched loss
fig, ax = plt.subplots(1, 2, figsize=(12, 4.5))
mean_r, lo, hi = summ["mean_ratio"].values, summ["min_ratio"].values, summ["max_ratio"].values
ax[0].errorbar(M_LIST, mean_r, yerr=[mean_r - lo, hi - mean_r], fmt="o-", capsize=4)
ax[0].axvline(rank_D, color="r", ls="--", label=f"rank(D) = {rank_D}")
ax[0].axhline(1, color="gray", ls=":")
ax[0].set_xscale("log"); ax[0].set_yscale("log")
ax[0].set_xlabel("m"); ax[0].set_ylabel("Loss(D,y,ã) / Loss(D,y,b)")
ax[0].set_title("(b) Loss ratio (mean, min/max of 5 runs)"); ax[0].legend()
sl = np.maximum(summ["mean_sketched_loss"].values, 1e-30)
ax[1].plot(M_LIST, sl, "s-")
ax[1].axvline(rank_D, color="r", ls="--", label=f"rank(D) = {rank_D}")
ax[1].set_xscale("log"); ax[1].set_yscale("log")
ax[1].set_xlabel("m"); ax[1].set_ylabel("‖SDã − Sy‖²  (mean)")
ax[1].set_title("(b) Sketched loss"); ax[1].legend()
plt.tight_layout(); plt.savefig(os.path.join(OUT, "fig_b_ratio_and_sketched_loss.png"), dpi=150); plt.close()

# Figure for (c): time vs m with full-solve line
plt.figure(figsize=(6, 4.5))
plt.plot(M_LIST, summ["mean_time_total"], "o-", label="sketch + solve (mean of 5)")
plt.plot(M_LIST, summ["mean_time_sketch"], "^--", label="draw S + form SD, Sy")
plt.plot(M_LIST, summ["mean_time_solve"], "v--", label="lstsq on sketch")
plt.axhline(t_full, color="r", ls="--", label="full lstsq (a)")
plt.xscale("log"); plt.yscale("log"); plt.xlabel("m"); plt.ylabel("time (s)")
plt.title("(c) Running time"); plt.legend(); plt.tight_layout()
plt.savefig(os.path.join(OUT, "fig_c_time.png"), dpi=150); plt.close()

# --------------------------------------------------------------------------
# (d) Residual norm preservation  ||Sv||^2 / ||v||^2
# --------------------------------------------------------------------------
say("\n=== (d) ||Sv||^2/||v||^2 for the full-solution residual ===")
v = D @ b - y
vv = float(v @ v)
fig, axs = plt.subplots(1, 3, figsize=(14, 4))
drows = []
for ax_, m in zip(axs, [50, 500, 5000]):
    vals = np.array([
        float(np.sum(countsketch_vector(v, m, np.random.default_rng([SEED, 4, m, t])) ** 2) / vv)
        for t in range(100)])
    drows.append(dict(m=m, mean=vals.mean(), std=vals.std(ddof=1)))
    ax_.hist(vals, bins=20, edgecolor="k")
    ax_.axvline(1, color="r", ls="--")
    ax_.set_title(f"m = {m}: mean={vals.mean():.4f}, std={vals.std(ddof=1):.4f}")
    ax_.set_xlabel("‖Sv‖² / ‖v‖²")
plt.tight_layout(); plt.savefig(os.path.join(OUT, "fig_d_hist.png"), dpi=150); plt.close()
Dres = pd.DataFrame(drows); Dres.to_csv(os.path.join(OUT, "d_summary.csv"), index=False)
say(Dres.to_string(index=False))

# --------------------------------------------------------------------------
# (e) CountSketch vs dense Gaussian on a 50,000-row subset, m = 500
# --------------------------------------------------------------------------
say("\n=== (e) CountSketch vs dense Gaussian, 50,000-row subset, m=500 ===")
idx = np.random.default_rng(SEED).choice(n, size=50000, replace=False)   # fixed once
Dp, yp = D[idx], y[idx]
Zp = np.asfortranarray(np.column_stack([Dp, yp]))
bp = lstsq(Dp, yp)
loss_p = loss(Dp, yp, bp)
say(f"Loss(D',y',b') = {loss_p:.6f}")
m = 500
erows = []
for rep in range(REPS):
    # (i) CountSketch
    rng = np.random.default_rng([SEED, 5, 1, rep])
    t0 = time.perf_counter()
    SZ = countsketch_matrix(Zp, m, rng)
    t_form = time.perf_counter() - t0
    a_t = lstsq(SZ[:, :d], SZ[:, d])
    erows.append(dict(method="CountSketch", rep=rep, t_draw_form=t_form,
                      ratio=loss(Dp, yp, a_t) / loss_p))
    # (ii) dense Gaussian N(0, 1/m)
    rng = np.random.default_rng([SEED, 5, 2, rep])
    t0 = time.perf_counter()
    S = rng.normal(0.0, 1.0 / np.sqrt(m), size=(m, 50000))
    SZ = S @ Zp                                      # forms SD' and Sy'
    t_form = time.perf_counter() - t0
    a_t = lstsq(SZ[:, :d], SZ[:, d])
    erows.append(dict(method="Dense Gaussian", rep=rep, t_draw_form=t_form,
                      ratio=loss(Dp, yp, a_t) / loss_p))
    del S
E = pd.DataFrame(erows)
E.to_csv(os.path.join(OUT, "e_all_runs.csv"), index=False)
Esum = E.groupby("method")[["t_draw_form", "ratio"]].agg(["mean", "std"])
Esum.to_csv(os.path.join(OUT, "e_summary.csv"))
say(E.to_string(index=False))
say("\nAveraged over 5 repetitions:\n" + Esum.to_string())

say(f"\nAll outputs written to ./{OUT}/")
